"""
Draw the schematic for dipole-868 with kicad-schematic-builder.

Coax feed J1 on the left, the antenna AE1 on the right: centre conductor to one half of the dipole,
shield to the other half.

Run with:  python schematic.py
"""

import sys
from pathlib import Path

from kicad_schematic_builder import Schematic, verify

HERE = Path(__file__).resolve().parent
PROJECT = "dipole-868"
NETLIST = HERE / f"{PROJECT}.net"
SCHEMATIC = HERE / f"{PROJECT}.kicad_sch"
SCHEMATIC_NETLIST = HERE / f"{PROJECT}-schematic.net"


def draw():
    sch = Schematic(NETLIST, project=PROJECT)
    X, Y = 127.0, 101.6  # AE1

    sch.place("AE1", X, Y, ref_at=(5.08, -2.54), value_at=(5.08, 0))
    a1, a2 = sch.pin("AE1", "1"), sch.pin("AE1", "2")
    sch.place("J1", X - 25.4, a1[1] + 7.62, ref_at=(0, -5.08), value_at=(0, 5.08))
    sig, shield = sch.pin("J1", "1"), sch.pin("J1", "2")

    sch.wire(sig, (a1[0], sig[1]), a1)
    sch.label("RF", sig[0] + 7.62, sig[1])
    sch.wire(shield, (shield[0], shield[1] + 5.08), (a2[0], shield[1] + 5.08), a2)
    sch.label("RF_SHIELD", shield[0] + 7.62, shield[1] + 5.08)
    return sch


if __name__ == "__main__":
    draw().write(SCHEMATIC, title="Half-Wave Dipole 868 MHz",
                 comment="Generated by schematic.py from the SKiDL netlist")
    sys.exit(0 if verify(SCHEMATIC, NETLIST, export_to=SCHEMATIC_NETLIST) else 1)
