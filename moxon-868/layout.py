"""
Build the single-sided PCB for moxon-868 from the schematic netlist.

Steps: write the antenna footprint from the simulated dimensions (moxon-868-dims.json, made by sim.py)
and the coax feed footprint, load them, assign nets, place, draw outline and holes, save, DRC.

Orientation on the board: the beam points to the top (-y). The driven element is at the top edge with
the feed gap in its middle, the reflector at the bottom. The coax pigtail runs from the feed straight
down along the centre line, across the reflector, held by two cable ties (2.2 mm hole pairs).
No tracks: J1's pads lie exactly on the ends of the two driven element halves.

Run with the system Python (it needs KiCad's pcbnew module):  /usr/bin/python3 layout.py
"""

import json
import re
import subprocess
import sys
from pathlib import Path

import pcbnew

HERE = Path(__file__).resolve().parent
PROJECT = "moxon-868"
NETLIST = HERE / f"{PROJECT}-schematic.net"
DIMS_FILE = HERE / f"{PROJECT}-dims.json"
BOARD_FILE = HERE / f"{PROJECT}.kicad_pcb"
PROJECT_FILE = HERE / f"{PROJECT}.kicad_pro"
DRC_REPORT = HERE / f"{PROJECT}-drc.rpt"
ETCH_MIRRORED = HERE / f"{PROJECT}-etch-mirrored.pdf"  # print this one, the transfer mirrors it back
ETCH_CHECK = HERE / f"{PROJECT}-etch-topview.pdf"  # as seen from the copper side, for checking

FP_DIR = HERE / f"{PROJECT}.pretty"
FP_LIBS = {PROJECT: str(FP_DIR)}
KICAD_FP_DIR = "/usr/share/kicad/footprints"

TRACK_WIDTH = 0.6
CLEARANCE = 0.4

GAP = 2.0  # feed gap in the middle of the driven element
FEED_PAD = 2.5  # length of J1's solder pads along the element
MARGIN_TOP = 4.0  # copper to board edge
MARGIN_SIDE = 8.0  # room for the M3 holes left and right of the tails
MARGIN_BOTTOM = 6.0  # room for the second cable tie below the reflector
TIE_HOLE_DX = 3.5  # cable tie holes either side of the coax (RG316: 2.5 mm)
TIE_Y_FEED = 10.0  # first cable tie below the feed point, inside the rectangle

# Feed point (middle of the driven element's centre line) on the board
X0, Y0 = 150.0, 100.0


def mm(v):
    return pcbnew.FromMM(v)


def pt(x, y):
    return pcbnew.VECTOR2I(mm(x), mm(y))


def load_dims():
    d = json.loads(DIMS_FILE.read_text())
    return d["board_mm"], d["w_trace_mm"], d


# Footprints ----------------------------------------------------------------------------------
def poly(points):
    return " ".join(f"(xy {x:.3f} {y:.3f})" for x, y in points)


def custom_pad(number, at, size, points):
    """SMD pad with a polygon shape; points relative to the pad position. Copper only (mask stays on)."""
    return (f'\t(pad "{number}" smd custom (at {at[0]:.3f} {at[1]:.3f}) (size {size[0]} {size[1]}) (layers "F.Cu")\n'
            f'\t\t(options (clearance outline) (anchor rect))\n'
            f'\t\t(primitives (gr_poly (pts {poly(points)}) (width 0) (fill yes))))\n')


def write_antenna_footprint(dims, w):
    """Origin = feed point. Driven element (two pads) at y=0, tails down by B; reflector at y=E, tails up by D."""
    a2, h, g2 = dims["A"] / 2, w / 2, GAP / 2
    b, d, e = dims["B"], dims["D"], dims["E"]
    anchor = (g2 + FEED_PAD / 2, 0.0)
    left = [(-g2, -h), (-a2 - h, -h), (-a2 - h, b), (-a2 + h, b), (-a2 + h, h), (-g2, h)]
    # Pad 2 is the mirror image of pad 1
    pad1 = [(x + anchor[0], y) for x, y in left]
    pad2 = [(-x - anchor[0], y) for x, y in left]
    reflector = [(-a2 - h, e - d), (-a2 + h, e - d), (-a2 + h, e - h), (a2 - h, e - h), (a2 - h, e - d),
                 (a2 + h, e - d), (a2 + h, e + h), (-a2 - h, e + h)]
    text = (
        '(footprint "Moxon_868"\n\t(version 20241229)\n\t(generator "layout.py")\n\t(layer "F.Cu")\n'
        f'\t(descr "Moxon rectangle 868 MHz, A {dims["A"]} B {dims["B"]} C {dims["C"]} D {dims["D"]} mm, '
        f'strips {w} mm, generated by layout.py")\n'
        '\t(attr smd exclude_from_bom)\n'
        f'\t(property "Reference" "REF**" (at 0 {e / 2 - 4:.2f} 0) (layer "F.SilkS") (effects (font (size 1.5 1.5) (thickness 0.2))))\n'
        f'\t(property "Value" "Moxon 868MHz" (at 0 {e / 2 + 4:.2f} 0) (layer "F.Fab") (effects (font (size 1.5 1.5) (thickness 0.2))))\n'
        f'\t(fp_text user "Moxon 868 MHz" (at 0 {e / 2:.2f} 0) (layer "F.SilkS") (effects (font (size 2 2) (thickness 0.3))))\n'
        # Arrow in the beam direction, above the reflector
        f'\t(fp_line (start -20 {e / 2 + 6:.2f}) (end -20 {e / 2 - 6:.2f}) (stroke (width 0.3) (type solid)) (layer "F.SilkS"))\n'
        f'\t(fp_poly (pts (xy -20 {e / 2 - 8:.2f}) (xy -21.5 {e / 2 - 5:.2f}) (xy -18.5 {e / 2 - 5:.2f})) '
        '(stroke (width 0.1) (type solid)) (fill yes) (layer "F.SilkS"))\n'
        f'\t(fp_poly (pts {poly(reflector)}) (stroke (width 0) (type solid)) (fill yes) (layer "F.Cu"))\n'
        + custom_pad("1", (-anchor[0], 0), (FEED_PAD, w), pad1)
        + custom_pad("2", anchor, (FEED_PAD, w), pad2)
        + ")\n")
    (FP_DIR / "Moxon_868.kicad_mod").write_text(text)


def write_feed_footprint(w):
    """Solder pads for the coax right on the feed gap: centre conductor pad 1 (left), shield pad 2 (right)."""
    x = GAP / 2 + FEED_PAD / 2
    text = (
        '(footprint "CoaxFeed_Gap2mm"\n\t(version 20241229)\n\t(generator "layout.py")\n\t(layer "F.Cu")\n'
        '\t(descr "Solder pads for a 50 Ohm coax pigtail (RG316/RG174) across a 2 mm feed gap, '
        'pad 1 centre conductor, pad 2 shield, cable leaves to +y")\n'
        '\t(attr smd)\n'
        '\t(property "Reference" "REF**" (at 0 -3.5 0) (layer "F.SilkS") (effects (font (size 1 1) (thickness 0.15))))\n'
        '\t(property "Value" "Coax" (at 0 6 0) (layer "F.Fab") (hide yes) (effects (font (size 1 1) (thickness 0.15))))\n'
        f'\t(pad "1" smd rect (at {-x:.3f} 0) (size {FEED_PAD} {w}) (layers "F.Cu" "F.Mask"))\n'
        f'\t(pad "2" smd rect (at {x:.3f} 0) (size {FEED_PAD} {w}) (layers "F.Cu" "F.Mask"))\n'
        # Cable path on the silkscreen
        '\t(fp_line (start -1.25 2.5) (end -1.25 8) (stroke (width 0.15) (type dash)) (layer "F.SilkS"))\n'
        '\t(fp_line (start 1.25 2.5) (end 1.25 8) (stroke (width 0.15) (type dash)) (layer "F.SilkS"))\n'
        f'\t(fp_rect (start {-x - FEED_PAD / 2 - 0.25:.3f} {-w / 2 - 0.25:.3f}) (end {x + FEED_PAD / 2 + 0.25:.3f} 2.5) '
        '(stroke (width 0.05) (type solid)) (fill no) (layer "F.CrtYd"))\n'
        ")\n")
    (FP_DIR / "CoaxFeed_Gap2mm.kicad_mod").write_text(text)


# Board ---------------------------------------------------------------------------------------
def parse_netlist(path):
    text = path.read_text()
    comps = []
    for block in re.split(r"\(comp\b", text[: text.index("(nets")])[1:]:
        ref = re.search(r'\(ref "([^"]+)"\)', block).group(1)
        value = re.search(r'\(value "([^"]*)"\)', block).group(1)
        footprint = re.search(r'\(footprint "([^"]+)"\)', block).group(1)
        comps.append((ref, value, footprint))
    nets = {}
    for block in re.split(r"\(net\b", text[text.index("(nets") + 5:])[1:]:
        name = re.search(r'\(name "([^"]*)"\)', block).group(1)
        nets[name] = re.findall(r'\(ref "([^"]+)"\)\s*\(pin "([^"]+)"\)', block)
    return comps, nets


def load_footprint(fp_id):
    lib, name = fp_id.split(":")
    lib_path = FP_LIBS.get(lib, f"{KICAD_FP_DIR}/{lib}.pretty")
    fp = pcbnew.FootprintLoad(lib_path, name)
    if fp is None:
        sys.exit(f"Footprint not found: {fp_id}")
    fp.SetFPIDAsString(fp_id)
    return fp


def add_rect(board, x0, y0, x1, y1, layer, width=0.1):
    for a, b in [((x0, y0), (x1, y0)), ((x1, y0), (x1, y1)), ((x1, y1), (x0, y1)), ((x0, y1), (x0, y0))]:
        seg = pcbnew.PCB_SHAPE(board)
        seg.SetShape(pcbnew.SHAPE_T_SEGMENT)
        seg.SetStart(pt(*a))
        seg.SetEnd(pt(*b))
        seg.SetLayer(layer)
        seg.SetWidth(mm(width))
        board.Add(seg)


def add_hole(board, ref, fp_id, x, y):
    fp = load_footprint(fp_id)
    fp.SetReference(ref)
    fp.SetBoardOnly(True)
    fp.Reference().SetVisible(False)
    fp.SetPosition(pt(x, y))
    board.Add(fp)


def build_board(dims, w):
    comps, nets = parse_netlist(NETLIST)
    board = pcbnew.NewBoard(str(BOARD_FILE))

    ds = board.GetDesignSettings()
    nc = ds.m_NetSettings.GetDefaultNetclass()
    nc.SetTrackWidth(mm(TRACK_WIDTH))
    nc.SetClearance(mm(CLEARANCE))
    ds.m_CopperEdgeClearance = mm(0.5)
    ds.SetCopperLayerCount(2)  # KiCad's minimum; B.Cu stays empty

    net_items = {}
    for name in nets:
        item = pcbnew.NETINFO_ITEM(board, name)
        board.Add(item)
        net_items[name] = item

    footprints = {}
    for ref, value, fp_id in comps:
        fp = load_footprint(fp_id)
        fp.SetReference(ref)
        fp.SetValue(value)
        fp.SetPosition(pt(X0, Y0))  # both footprints have their origin on the feed point
        board.Add(fp)
        footprints[ref] = fp

    for name, nodes in nets.items():
        for ref, pin in nodes:
            for pad in footprints[ref].Pads():
                if pad.GetNumber() == pin:
                    pad.SetNet(net_items[name])
    footprints["J1"].Reference().SetPosition(pt(X0 + 6, Y0 + 4))

    h, a2, e = w / 2, dims["A"] / 2, dims["E"]
    bx0, bx1 = X0 - a2 - h - MARGIN_SIDE, X0 + a2 + h + MARGIN_SIDE
    by0, by1 = Y0 - h - MARGIN_TOP, Y0 + e + h + MARGIN_BOTTOM
    add_rect(board, bx0, by0, bx1, by1, pcbnew.Edge_Cuts)

    # M3 holes left and right at half depth, use nylon screws (metal next to the tails detunes)
    add_hole(board, "H1", "MountingHole:MountingHole_3.2mm_M3", bx0 + 3.5, Y0 + e / 2)
    add_hole(board, "H2", "MountingHole:MountingHole_3.2mm_M3", bx1 - 3.5, Y0 + e / 2)
    # Cable tie hole pairs on the centre line: below the feed and below the reflector
    tie_y2 = Y0 + e + h + MARGIN_BOTTOM / 2
    for i, (dx, y) in enumerate([(-TIE_HOLE_DX, Y0 + TIE_Y_FEED), (TIE_HOLE_DX, Y0 + TIE_Y_FEED),
                                 (-TIE_HOLE_DX, tie_y2), (TIE_HOLE_DX, tie_y2)], start=3):
        add_hole(board, f"H{i}", "MountingHole:MountingHole_2.2mm_M2", X0 + dx, y)
    return board, (bx0, by0, bx1, by1)


def write_project_rules():
    """Netclass rules live in the .kicad_pro; without them the DRC checks against KiCad's 0.2 mm default."""
    pro = json.loads(PROJECT_FILE.read_text()) if PROJECT_FILE.exists() else {}
    pro.setdefault("meta", {"filename": PROJECT_FILE.name, "version": 3})
    net_settings = pro.setdefault("net_settings", {"meta": {"version": 4}})
    classes = net_settings.setdefault("classes", [])
    default = next((c for c in classes if c.get("name") == "Default"), None)
    if default is None:
        default = {"name": "Default"}
        classes.append(default)
    default.update({"clearance": CLEARANCE, "track_width": TRACK_WIDTH})
    PROJECT_FILE.write_text(json.dumps(pro, indent=2) + "\n")


def export_etching():
    """F.Cu + board outline in black, holes left open as drill marks."""
    for path, mirror in ((ETCH_MIRRORED, True), (ETCH_CHECK, False)):
        cmd = ["kicad-cli", "pcb", "export", "pdf", "--layers", "F.Cu,Edge.Cuts", "--mode-single",
               "--black-and-white", "--drill-shape-opt", "2", "-o", str(path), str(BOARD_FILE)]
        if mirror:
            cmd.insert(4, "--mirror")
        subprocess.run(cmd, check=True, capture_output=True)
        print("Etching mask:", path.name)


def main():
    dims, w, raw = load_dims()
    FP_DIR.mkdir(exist_ok=True)
    write_antenna_footprint(dims, w)
    write_feed_footprint(w)
    write_project_rules()
    board, (bx0, by0, bx1, by1) = build_board(dims, w)
    board.Save(str(BOARD_FILE))
    print(f"Moxon A {dims['A']} B {dims['B']} C {dims['C']} D {dims['D']} E {dims['E']} mm "
          f"(K_FR4 {raw['k_fr4']}), board {bx1 - bx0:.1f} x {by1 - by0:.1f} mm")
    drc = subprocess.run(["kicad-cli", "pcb", "drc", "--schematic-parity", "--severity-error", "--exit-code-violations",
                          "-o", str(DRC_REPORT), str(BOARD_FILE)], capture_output=True, text=True)
    print(drc.stdout.strip())
    if drc.returncode:
        sys.exit(f"DRC errors, no etching export (see {DRC_REPORT.name})")
    export_etching()


if __name__ == "__main__":
    main()
